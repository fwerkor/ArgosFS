#!/usr/bin/env python3
"""Version validation and deterministic AUR metadata generation for ArgosFS."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import subprocess
import sys
import tomllib

REPO = Path(__file__).resolve().parents[2]
STABLE_VERSION = re.compile(r"(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)\Z")
ARCHES = ("x86_64", "aarch64")
RELEASE_URL = "https://github.com/fwerkor/ArgosFS/releases/download"


def manifest_version() -> str:
    with (REPO / "Cargo.toml").open("rb") as source:
        return tomllib.load(source)["package"]["version"]


def verify_version(requested: str) -> str:
    version = requested or manifest_version()
    if not STABLE_VERSION.fullmatch(version):
        raise ValueError(f"Expected stable x.y.z version, got {version!r}")
    if manifest_version() != version:
        raise ValueError(f"Cargo.toml is {manifest_version()}, not {version}")
    return version


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def expected_assets(version: str) -> list[str]:
    return [
        f"argosfs-{version}-source.tar.gz",
        *(f"argosfs-{version}-{arch}-unknown-linux-gnu.tar.gz" for arch in ARCHES),
    ]


def verify_dist(version: str, dist: Path) -> dict[str, str]:
    names = expected_assets(version)
    digests = {name: sha256(dist / name) for name in names}
    manifest = dist / "SHA256SUMS"
    if manifest.exists():
        expected = "".join(f"{digests[name]}  {name}\n" for name in sorted(names))
        if manifest.read_text() != expected:
            raise ValueError("SHA256SUMS does not match release archive contents")
    return digests


def aur_shared(name: str, version: str) -> str:
    return (
        "# Maintained by the ArgosFS project; generated by scripts/release/release.py.\n"
        "# Edit the generator, not this file.\n"
        f"pkgname={name}\n"
        f"pkgver={version}\n"
        "pkgrel=1\n"
        "pkgdesc='Self-driving erasure-coded Linux filesystem with FUSE frontend'\n"
        "arch=('x86_64' 'aarch64')\n"
        "url='https://argosfs.org'\n"
        "license=('Apache-2.0')\n"
        "depends=('fuse3' 'glibc')\n"
        "optdepends=('smartmontools: SMART disk telemetry')\n"
    )


def aur_source(version: str, digests: dict[str, str]) -> str:
    name = f"argosfs-{version}-source.tar.gz"
    return aur_shared("argosfs", version) + (
        "makedepends=('cargo' 'pkgconf')\n"
        f'source=("{name}::{RELEASE_URL}/v${{pkgver}}/{name}")\n'
        f"sha256sums=('{digests[name]}')\n"
        "\n"
        "prepare() {\n"
        "  cd \"${srcdir}/argosfs-${pkgver}\"\n"
        "  export CARGO_HOME=\"${srcdir}/cargo-home\"\n"
        "  cargo fetch --locked\n"
        "}\n"
        "\n"
        "build() {\n"
        "  cd \"${srcdir}/argosfs-${pkgver}\"\n"
        "  export CARGO_HOME=\"${srcdir}/cargo-home\"\n"
        "  export CARGO_TARGET_DIR=\"${srcdir}/target\"\n"
        "  cargo build --release --locked --offline --bin argosfs\n"
        "}\n"
        "\n"
        "package() {\n"
        "  cd \"${srcdir}/argosfs-${pkgver}\"\n"
        "  install -Dm755 \"${srcdir}/target/release/argosfs\" \"${pkgdir}/usr/bin/argosfs\"\n"
        "  install -Dm644 LICENSE \"${pkgdir}/usr/share/licenses/argosfs/LICENSE\"\n"
        "  install -d \"${pkgdir}/usr/share/argosfs\"\n"
        "  cp -r integrations \"${pkgdir}/usr/share/argosfs/\"\n"
        "}\n"
    )


def aur_binary(version: str, digests: dict[str, str]) -> str:
    result = aur_shared("argosfs-bin", version) + (
        "provides=('argosfs')\n"
        "conflicts=('argosfs')\n"
    )
    for arch in ARCHES:
        name = f"argosfs-{version}-{arch}-unknown-linux-gnu.tar.gz"
        result += f'source_{arch}=("{name}::{RELEASE_URL}/v${{pkgver}}/{name}")\n'
        result += f"sha256sums_{arch}=('{digests[name]}')\n"
    return result + (
        "\n"
        "package() {\n"
        "  install -Dm755 \"${srcdir}/argosfs\" \"${pkgdir}/usr/bin/argosfs\"\n"
        "  install -Dm644 \"${srcdir}/LICENSE\" \"${pkgdir}/usr/share/licenses/argosfs-bin/LICENSE\"\n"
        "  install -d \"${pkgdir}/usr/share/argosfs\"\n"
        "  cp -r \"${srcdir}/integrations\" \"${pkgdir}/usr/share/argosfs/\"\n"
        "}\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    subparsers = parser.add_subparsers(dest="action", required=True)
    check = subparsers.add_parser("check")
    check.add_argument("--version", default="")
    check.add_argument("--git-sha", default="")
    aur = subparsers.add_parser("aur")
    aur.add_argument("--version", required=True)
    aur.add_argument("--dist", type=Path, required=True)
    aur.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    version = verify_version(args.version)
    if args.action == "check":
        if args.git_sha:
            sha = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO, text=True).strip()
            if sha != args.git_sha:
                raise ValueError(f"Checkout {sha} does not match requested commit {args.git_sha}")
            tag = f"v{version}"
            present = subprocess.run(["git", "rev-parse", "--verify", "-q", f"refs/tags/{tag}^{{commit}}"],
                                     cwd=REPO, text=True, capture_output=True, check=False)
            if present.returncode == 0 and present.stdout.strip() != sha:
                raise ValueError(f"Existing {tag} tag points to another commit")
        print(version)
        return

    digests = verify_dist(version, args.dist)
    for name, builder in (("argosfs", aur_source), ("argosfs-bin", aur_binary)):
        output = args.out / name
        output.mkdir(parents=True, exist_ok=True)
        (output / "PKGBUILD").write_text(builder(version, digests))


if __name__ == "__main__":
    try:
        main()
    except (ValueError, FileNotFoundError, subprocess.CalledProcessError) as exc:
        sys.exit(str(exc))
